export function mapTransactionToExportRow(transaction, currency = 'ILS') {
  const tx = { ...transaction, currency: currencyOf(transaction), boardAmount: boardAmount(transaction, currency),
    boardCurrency: currency, rate: transaction.conversion?.rate ?? '', rateDate: transaction.conversion?.rateDate ?? '',
    source: transaction.conversion?.source ?? '', provider: transaction.conversion?.provider ?? '' };
  return COLUMNS.map(column => {
    const value = tx[column.key] ?? '';
    if (column.type === 'date') {
      const date = parseExportDate(value);
      // Excel's date system cannot faithfully display dates before 1900.
      if (date && date.getUTCFullYear() >= 1900) return date;
      return excelText(date ? date.toISOString() : value);
    }
    if (column.type === 'exact') {
      const moneyCurrency = column.key === 'amount' ? tx.currency : column.key === 'boardAmount' ? currency : undefined;
      return excelDecimal(value, { currency: moneyCurrency });
    }
    if (column.type === 'number') {
      if (value === '') return '';
      const number = Number(value);
      return Number.isSafeInteger(number) ? number : excelText(value);
    }
    return excelText(column.map ? column.map(value) : value);
  });
}

export function sanitizeWorksheetName(name, fallback = 'Sheet') {
  const clean = value => cleanExcelText(value).normalize('NFC')
    .replace(/[\\/?*[\]:]/g, ' ').replace(/\s+/g, ' ').trim().replace(/^'+|'+$/g, '').trim();
  const base = clean(name) || clean(fallback) || 'Sheet';
  return truncateUnicode(base, 31).replace(/'+$/g, '').trim() || 'Sheet';
}

export function sanitizeFilename(name, fallback = 'board') {
  const cleaned = cleanExcelText(name).replace(/[<>:"/\\|?*\t\r\n]/g, ' ')
    .replace(/\s+/g, ' ').trim().replace(/[. ]+$/g, '');
  const result = truncateUnicode(cleaned, 150).replace(/[. ]+$/g, '') || fallback;
  return /^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)/i.test(result) ? `_${result}` : result;
}

function sheetNameKey(name) {
  return name.normalize('NFC').toLowerCase();
}

function stableNameSuffix(id) {
  let hash = 2166136261;
  for (const char of id) hash = Math.imul(hash ^ char.codePointAt(0), 16777619) >>> 0;
  return hash.toString(36);
}

function allocateSheetName(node, usedNames) {
  const base = sanitizeWorksheetName(node.tabPath);
  let candidate = base;
  // Reserve stable distinguishing space whenever truncation or a collision occurs.
  // The counter also resolves the (rare) hash collision, in deterministic tree order.
  if (node.tabPath.length > 31 || usedNames.has(sheetNameKey(candidate))) {
    const token = stableNameSuffix(node.id);
    let counter = 0;
    do {
      const suffix = `~${token}${counter ? `-${counter}` : ''}`;
      candidate = `${truncateUnicode(base, 31 - suffix.length)}${suffix}`;
      counter += 1;
    } while (usedNames.has(sheetNameKey(candidate)));
  }
  usedNames.add(sheetNameKey(candidate));
  return candidate;
}

function sheetLink(text, name) {
  // No user-authored formulas; quote the generated sheet name for an internal link.
  return { text: excelText(text), hyperlink: `#'${name.replace(/'/g, "''")}'!A1` };
}

function mergedText(worksheet, rowNumber, text, lastColumn, { size = 11, bold = false } = {}) {
  worksheet.mergeCells(rowNumber, 1, rowNumber, lastColumn);
  const cell = worksheet.getCell(rowNumber, 1);
  cell.value = excelText(text);
  cell.font = { size, bold, color: { argb: 'FF334155' } };
  cell.alignment = { horizontal: 'right', vertical: 'middle', wrapText: true };
  worksheet.getRow(rowNumber).height = rowNumber === 1 ? 42 : 32;
}

function styleHeader(worksheet, rowNumber, count, color = 'FF1E3A8A') {
  worksheet.getRow(rowNumber).height = 32;
  for (let column = 1; column <= count; column++) {
    const cell = worksheet.getCell(rowNumber, column);
    cell.font = { bold: true, size: 11, color: { argb: 'FFFFFFFF' } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: color } };
    cell.border = TABLE_BORDER;
    cell.alignment = { vertical: 'middle', horizontal: 'right', wrapText: true };
  }
}

function styleDataRow(row, columnCount, striped) {
  for (let column = 1; column <= columnCount; column++) {
    const cell = row.getCell(column);
    cell.border = TABLE_BORDER;
    cell.alignment = { vertical: 'middle', horizontal: 'right' };
    if (striped) cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF1F5F9' } };
  }
}

function configureSheet(worksheet, columns, lastRow) {
  worksheet.columns = columns.map(column => ({ key: column.key, width: column.width }));
  worksheet.views = [{ state: 'frozen', ySplit: HEADER_ROW, rightToLeft: true }];
  worksheet.autoFilter = {
    from: { row: HEADER_ROW, column: 1 },
    to: { row: Math.max(HEADER_ROW, lastRow), column: columns.length },
  };
  worksheet.pageSetup = { orientation: 'landscape', fitToPage: true, fitToWidth: 1, fitToHeight: 0,
    printTitlesRow: `1:${HEADER_ROW}` };
}

function appendFooterRow(worksheet, columnCount) {
  worksheet.addRow([]).height = 8;
  const row = worksheet.addRow([{ text: FOOTER_TEXT, hyperlink: FOOTER_URL }]);
  worksheet.mergeCells(row.number, 1, row.number, columnCount);
  const cell = row.getCell(1);
  cell.font = { size: 10, color: { argb: 'FF64748B' }, underline: true };
  cell.alignment = { horizontal: 'center', vertical: 'middle', wrapText: true };
  row.height = 32;
}

function addTransactionWorksheet(workbook, node, generatedAt) {
  const sheet = workbook.addWorksheet(node.sheetName);
  const count = COLUMNS.length;
  configureSheet(sheet, COLUMNS, HEADER_ROW + node.directCount);
  mergedText(sheet, 1, node.path, count, { size: 16, bold: true });
  mergedText(sheet, 2, `מטבע הלוח: ${node.currency} | עסקאות ישירות: ${node.directCount} | נוצר: ${generatedAt}`, count);
  mergedText(sheet, 3, PRECISION_TEXT, count);
  sheet.getCell(4, 1).value = sheetLink('חזרה לסיכום', SUMMARY_NAME);
  sheet.getCell(4, 1).font = { color: { argb: 'FF2563EB' }, underline: true };
  sheet.getRow(HEADER_ROW).values = COLUMNS.map(column => column.header);
  styleHeader(sheet, HEADER_ROW, count);
  node.transactions.forEach((tx, index) => {
    const row = sheet.addRow(mapTransactionToExportRow(tx, node.currency));
    styleDataRow(row, count, index % 2 === 1);
    COLUMNS.forEach((column, columnIndex) => {
      const cell = row.getCell(columnIndex + 1);
      cell.alignment = { vertical: 'middle', horizontal: column.alignment || 'right', wrapText: !!column.wrapText };
      if (column.type === 'exact') {
        const currency = column.key === 'amount' ? currencyOf(tx) : column.key === 'boardAmount' ? node.currency : undefined;
        styleDecimalCell(cell, currency);
      } else if (column.type === 'number' && typeof cell.value === 'number') cell.numFmt = '0';
      else if (column.type === 'date' && cell.value instanceof Date) cell.numFmt = 'dd-mm-yyyy';
      else cell.numFmt = '@';
    });
  });
  // Trusted totals are outside the filterable transaction range.
  sheet.addRow([]);
  const totalRow = sheet.addRow(['סה״כ עסקאות ישירות במטבע הלוח', '', '', '', excelDecimal(node.directTotal, { currency: node.currency }), node.currency]);
  sheet.mergeCells(totalRow.number, 1, totalRow.number, 4);
  totalRow.getCell(1).alignment = { horizontal: 'right', vertical: 'middle', wrapText: true };
  totalRow.height = 28;
  totalRow.font = { bold: true };
  styleDecimalCell(totalRow.getCell(5), node.currency);
  appendFooterRow(sheet, count);
}

function stylePathCell(cell, node) {
  cell.alignment = { vertical: 'middle', horizontal: 'right', wrapText: true, indent: Math.min(node.depth, 7) };
  if (node.sheetName) cell.font = { color: { argb: 'FF2563EB' }, underline: true, bold: node.depth === 0 };
  else cell.font = { bold: node.depth === 0 };
}

function pathRowHeight(node) {
  const lineWidth = 50 - Math.min(node.depth, 7) * 3;
  const lines = cleanExcelText(node.path).split(/\r?\n/).reduce((count, line) => count + Math.max(1, Math.ceil(line.length / lineWidth)), 0);
  return Math.min(409, Math.max(32, lines * 16));
}

function boardPathValue(node) {
  return node.sheetName ? sheetLink(node.path, node.sheetName) : excelText(node.path);
}

function buildSummarySheet(workbook, nodes, generatedAt) {
  const sheet = workbook.addWorksheet(SUMMARY_NAME);
  const columns = [
    { header: 'נתיב הלוח המלא', width: 56 },
    { header: 'מטבע הלוח', width: 14 },
    { header: 'עסקאות ישירות', width: 16 },
    { header: 'עסקאות כולל לוחות משנה', width: 20 },
    { header: 'סכום ישיר במטבע הלוח', width: 24 },
    { header: 'סכום כולל לוחות משנה', width: 28 },
  ];
  configureSheet(sheet, columns, HEADER_ROW + nodes.length);
  mergedText(sheet, 1, `סיכום — ${nodes[0].path}`, columns.length, { size: 16, bold: true });
  const scopeText = nodes[0].recursiveCount ? `${nodes[0].recursiveCount} עסקאות` : 'אין עסקאות בלוח או בלוחות המשנה';
  mergedText(sheet, 2, `${nodes.length} לוחות | ${scopeText} | נוצר: ${generatedAt}`, columns.length);
  mergedText(sheet, 3, PRECISION_TEXT, columns.length);
  mergedText(sheet, 4, 'סכומים כוללים חופפים בין הורה לצאצא — אין לסכום את שורות הסיכום. מטבעות שונים מוצגים בנפרד בטבלה שלהלן; לא בוצעה המרה נוספת.', columns.length);
  sheet.getRow(HEADER_ROW).values = columns.map(column => column.header);
  styleHeader(sheet, HEADER_ROW, columns.length, 'FF0F766E');
  const mixedNodes = [];
  nodes.forEach((node, index) => {
    const currencies = Object.keys(node.recursiveTotals).sort();
    const mixed = currencies.length > 1;
    if (mixed) mixedNodes.push(node);
    const row = sheet.addRow([
      boardPathValue(node), node.currency, node.directCount, node.recursiveCount,
      excelDecimal(node.directTotal, { currency: node.currency }),
      mixed ? 'פירוט לפי מטבע בהמשך' : excelDecimal(node.recursiveTotals[node.currency], { currency: node.currency }),
    ]);
    styleDataRow(row, columns.length, index % 2 === 1);
    row.height = pathRowHeight(node);
    stylePathCell(row.getCell(1), node);
    row.getCell(3).numFmt = row.getCell(4).numFmt = '0';
    styleDecimalCell(row.getCell(5), node.currency);
    if (!mixed) styleDecimalCell(row.getCell(6), node.currency);
  });
  if (mixedNodes.length) {
    sheet.addRow([]);
    const titleRow = sheet.addRow([]);
    mergedText(sheet, titleRow.number, 'פירוט סכומים לפי מטבע — לוחות עם מספר מטבעות', columns.length, { bold: true });
    const header = sheet.addRow(['נתיב הלוח המלא', 'מטבע הסכום', '', '', 'סכום ישיר', 'סכום כולל לוחות משנה']);
    styleHeader(sheet, header.number, columns.length, 'FF0F766E');
    let index = 0;
    for (const node of mixedNodes) {
      for (const currency of Object.keys(node.recursiveTotals).sort()) {
        const direct = currency === node.currency ? node.directTotal : fromMinor(0n, currency);
        const row = sheet.addRow([boardPathValue(node), currency, '', '',
          excelDecimal(direct, { currency }), excelDecimal(node.recursiveTotals[currency], { currency })]);
        styleDataRow(row, columns.length, index++ % 2 === 1);
        stylePathCell(row.getCell(1), node);
        row.height = pathRowHeight(node);
        styleDecimalCell(row.getCell(5), currency);
        styleDecimalCell(row.getCell(6), currency);
      }
    }
  }
  appendFooterRow(sheet, columns.length);
}

function triggerWorkbookDownload(buffer, filename) {
  const blob = new Blob([buffer], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
  const url = window.URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  try {
    document.body.appendChild(link);
    link.click();
  } finally {
    link.remove();
    window.setTimeout(() => window.URL.revokeObjectURL(url), 0);
  }
}

export async function exportBoardToExcel({ boardId, boardCount, worksheets }) {
  const ExcelJS = window.ExcelJS;
  if (!ExcelJS?.Workbook) throw new Error('ספריית הייצוא לא נטענה. רענן את העמוד ונסה שוב.');
  const nodes = prepareExcelHierarchy({ boardId, boardCount, worksheets });
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'OF8 Expense Management';
  workbook.lastModifiedBy = 'OF8 Expense Management';
  workbook.created = workbook.modified = new Date();
  workbook.title = cleanExcelText(nodes[0].title);
  workbook.subject = 'סיכום לוחות ועסקאות';
  const generatedAt = workbook.created.toISOString();
  const usedNames = new Set([sheetNameKey(SUMMARY_NAME), 'summary', 'history']);
  for (const node of nodes) {
    if (node.directCount) node.sheetName = allocateSheetName(node, usedNames);
  }
  buildSummarySheet(workbook, nodes, generatedAt);
  for (const node of nodes) {
    if (node.directCount) addTransactionWorksheet(workbook, node, generatedAt);
  }
  const buffer = await workbook.xlsx.writeBuffer();
  triggerWorkbookDownload(buffer, `${sanitizeFilename(nodes[0].title)}.xlsx`);
}
